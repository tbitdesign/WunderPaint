export function createLayerEffects( helpers ) {
	return SPEC.map( ( spec ) => {
		const params = {
			intensity: {
				label: __( 'Intensity', 'wunderpaint' ),
				min: 0,
				max: 100,
				default: spec.intensity,
				unit: '%',
			},
			scale: {
				label: __( 'Scale', 'wunderpaint' ),
				min: 2,
				max: 100,
				default: spec.size,
			},
		};
		if ( spec.angle ) {
			params.angle = {
				label: __( 'Angle', 'wunderpaint' ),
				min: 0,
				max: 360,
				default: 35,
				unit: '°',
			};
		}
		if ( spec.seed ) {
			params.seed = {
				label: __( 'Variant', 'wunderpaint' ),
				min: 1,
				max: 99,
				default: 7,
			};
		}
		if ( spec.ink ) {
			params.ink = {
				label: __( 'Ink', 'wunderpaint' ),
				type: 'color',
				default: '#233b57',
			};
		}
		if ( spec.paper ) {
			params.paper = {
				label: __( 'Paper', 'wunderpaint' ),
				type: 'color',
				default: '#f4dfb5',
			};
		}
		const defaults = Object.fromEntries(
			Object.entries( params ).map( ( [ key, schema ] ) => [
				key,
				schema.default,
			] )
		);
		return {
			id: 'finish-' + spec.mode,
			label: spec.label,
			group: spec.group,
			collection: true,
			params,
			apply: ( image, values ) =>
				applyCreativeEffect(
					image,
					spec.mode,
					{ ...defaults, ...values },
					helpers
				),
		};
	} );
}
