/**
 * EU AI-labelling emblems (v1.400.0).
 *
 * The European Commission publishes three emblems for disclosing AI
 * involvement in content, each in four color variants. They are free to use
 * without attribution. The files under `assets/eu-ai-labels/` are the
 * Commission's originals, byte for byte - nothing is redrawn here.
 *
 * NOTHING in the editor applies these on its own. There is no detection, no
 * suggestion and no default: an emblem is stamped only when the user ticks
 * the box in the Export/Save dialog, or inserts one as a normal layer. The
 * law asks for disclosure on content that could pass for real, not on every
 * illustration, and only the person exporting knows which one they made.
 *
 * Every file declares a `viewBox` and NO width/height, so anything that
 * rasterizes one has to go through `sizedSvgUrl()` first (svg-intrinsic.js) -
 * otherwise `naturalWidth` is 0 and `applyWatermark()` returns untouched.
 *
 * Leaf module: pure data plus one thin wrapper over the watermark placement
 * math, so node-canvas can verify it.
 */

import { __ } from '@wordpress/i18n';

import { applyWatermark } from './watermark';

/**
 * The three emblems, in the Commission's own wording.
 *
 * `ratio` is width/height straight out of each file's viewBox. `scale` is the
 * default size as a percent of the export width, picked per motif so all
 * three end up at roughly the same optical HEIGHT: the basic emblem is
 * square, the other two are long bars, and one shared percentage would make
 * the bars tower over the square one.
 */
export const MOTIFS = [
	{
		id: 'ai',
		file: 'ai',
		ratio: 566.93 / 566.93,
		scale: 8,
		// The basic emblem makes the vaguer claim "AI was involved", so it
		// maps onto the weaker of the two source types. Overstating is the
		// worse error of the two.
		sourceType: 'compositeWithTrainedAlgorithmicMedia',
		label: () => __( 'Basic emblem', 'wunderpaint' ),
		hint: () =>
			__( 'AI was involved in creating this content.', 'wunderpaint' ),
	},
	{
		id: 'generated',
		file: 'ai-generated',
		ratio: 1789.84 / 566.93,
		scale: 25,
		sourceType: 'trainedAlgorithmicMedia',
		label: () => __( 'Fully AI-generated', 'wunderpaint' ),
		hint: () =>
			__(
				'The whole image was generated by AI, with no human-made elements.',
				'wunderpaint'
			),
	},
	{
		id: 'modified',
		file: 'ai-modified',
		ratio: 1700.79 / 566.93,
		scale: 25,
		sourceType: 'compositeWithTrainedAlgorithmicMedia',
		label: () => __( 'Partially AI-modified', 'wunderpaint' ),
		hint: () =>
			__(
				'Existing human-made content was partially changed with AI.',
				'wunderpaint'
			),
	},
];

/** Color variants, one file each. */
export const VARIANTS = [
	{ id: 'black', suffix: 'black', label: () => __( 'Black', 'wunderpaint' ) },
	{
		id: 'black-transparent',
		suffix: 'black-transparent',
		label: () => __( 'Black, semi-transparent', 'wunderpaint' ),
	},
	{ id: 'white', suffix: 'white', label: () => __( 'White', 'wunderpaint' ) },
	{
		id: 'white-transparent',
		suffix: 'white-transparent',
		label: () => __( 'White, semi-transparent', 'wunderpaint' ),
	},
];

/** Where the stamp sits by default: bottom right, like a signature. */
export const DEFAULT_PLACEMENT = { pos: 'br', margin: 16 };

/**
 * Look up a motif by id, falling back to the basic emblem.
 *
 * @param {string} id Motif id.
 * @return {Object} Motif descriptor.
 */
export function motif( id ) {
	return MOTIFS.find( ( m ) => m.id === id ) || MOTIFS[ 0 ];
}

/**
 * Relative asset path of one emblem file.
 *
 * @param {string} motifId   Motif id.
 * @param {string} variantId Variant id.
 * @return {string} Path below the plugin folder.
 */
export function labelPath( motifId, variantId ) {
	const m = motif( motifId );
	const v = VARIANTS.find( ( x ) => x.id === variantId ) || VARIANTS[ 0 ];
	return `assets/eu-ai-labels/${ m.file }-${ v.suffix }.svg`;
}

/**
 * Full URL of one emblem file.
 *
 * `pluginUrl` carries its trailing slash (see gazetteer.js), so the path is
 * appended as-is.
 *
 * @param {string} motifId   Motif id.
 * @param {string} variantId Variant id.
 * @return {string} Absolute URL.
 */
export function labelUrl( motifId, variantId ) {
	const base =
		( typeof window !== 'undefined' && window.WPIE?.pluginUrl ) || '';
	return base + labelPath( motifId, variantId );
}

/**
 * Every emblem as an insertable tile, for the Brand Kits section of the
 * library. Built here rather than in a screen so the tray and the modal
 * cannot drift apart - they render the same list.
 *
 * `dark` marks the variants that vanish on a light tile background and need
 * a contrasting swatch behind the preview.
 *
 * @return {Array<Object>} Tiles: {id, motifId, variantId, url, name, dark}.
 */
export function labelTiles() {
	return MOTIFS.flatMap( ( m ) =>
		VARIANTS.map( ( v ) => ( {
			id: `${ m.id }-${ v.id }`,
			motifId: m.id,
			variantId: v.id,
			url: labelUrl( m.id, v.id ),
			name: `${ m.label() } - ${ v.label() }`,
			dark: v.id.startsWith( 'white' ),
		} ) )
	);
}

/**
 * Stamp an emblem onto a rendered export canvas (mutates it).
 *
 * Deliberately opaque: the semi-transparent look is a separate FILE from the
 * Commission, not a slider. A disclosure that the user dialed down to 20%
 * opacity would defeat its own purpose, so opacity is not offered here.
 *
 * @param {HTMLCanvasElement}                  canvas Rendered export.
 * @param {HTMLImageElement|HTMLCanvasElement} img    Loaded emblem.
 * @param {Object}                             opts   {pos, scale, margin}.
 * @return {HTMLCanvasElement} The same canvas.
 */
export function applyAiLabel( canvas, img, opts = {} ) {
	return applyWatermark( canvas, img, {
		...DEFAULT_PLACEMENT,
		...opts,
		opacity: 100,
	} );
}
