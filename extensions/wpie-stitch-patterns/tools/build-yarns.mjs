/**
 * Builds src/yarns.js - the thread, bead and yarn color sets the legend
 * names - from the craft-color-codes package (MakeBead, data CC BY 4.0;
 * the Hama and Perler values MIT via maxcleme/beadcolors). See
 * ATTRIBUTION.md.
 *
 *   npm pack craft-color-codes@1.0.0 && tar xzf craft-color-codes-1.0.0.tgz
 *   node tools/build-yarns.mjs <path to the unpacked package>
 *
 * Only data is read; nothing from the package is executed or shipped.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = process.argv[ 2 ];
if ( ! pkg ) {
	console.error( 'usage: node tools/build-yarns.mjs <craft-color-codes package dir>' );
	process.exit( 1 );
}
const SETS = [
	[ 'dmc', 'dmc-floss', 'DMC', 'skein' ],
	[ 'hama', 'hama-midi', 'Hama', 'bead' ],
	[ 'perler', 'perler-midi', 'Perler', 'bead' ],
	[ 'redheart', 'red-heart-super-saver', 'Red Heart', 'skein' ],
	[ 'delica', 'miyuki-delica', 'Delica', 'bead' ],
];
const out = [];
for ( const [ id, file, brand ] of SETS ) {
	const d = JSON.parse( readFileSync( join( pkg, 'data', 'json', file + '.json' ), 'utf8' ) );
	out.push(
		`\t${ id }: { brand: ${ JSON.stringify( brand ) }, colors: [\n` +
			d.colors
				// Discontinued beads cannot be bought any more.
				.filter( ( c ) => ! c.discontinued )
				.map( ( c ) => `\t\t[ ${ JSON.stringify( c.code ) }, ${ JSON.stringify( c.name ) }, ${ c.rgb.join( ', ' ) } ],` )
				.join( '\n' ) +
			'\n\t] },'
	);
}
const here = dirname( fileURLToPath( import.meta.url ) );
writeFileSync(
	join( here, '..', 'src', 'yarns.js' ),
	`/**
 * Thread, bead and yarn colors by maker number (generated by
 * tools/build-yarns.mjs - do not edit by hand).
 *
 * Color data: craft-color-codes by MakeBead (https://makebead.com),
 * CC BY 4.0; the Hama and Perler values from maxcleme/beadcolors, MIT.
 * The values are close approximations of the real colors. Maker names and
 * numbers are trademarks of their owners; this is not affiliated with or
 * endorsed by any of them. See ATTRIBUTION.md.
 *
 * Each color: [ number, name, r, g, b ].
 */
export const YARN_DATA = {
${ out.join( '\n' ) }
};
`
);
console.log( 'wrote src/yarns.js' );
