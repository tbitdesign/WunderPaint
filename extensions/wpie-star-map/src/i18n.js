export const LOCALE = (
	( window.WPIE && window.WPIE.locale ) ||
	document.documentElement.lang ||
	'en'
).toLowerCase();

/**
 * WordPress locales use underscores (en_US) but Intl requires BCP-47
 * tags (en-US) and throws a RangeError otherwise.
 */
export const INTL_LOCALE = ( () => {
	const tag = LOCALE.replace( /_/g, '-' );
	for ( const candidate of [ tag, tag.split( '-' )[ 0 ], 'en' ] ) {
		try {
			Intl.DateTimeFormat.supportedLocalesOf( candidate );
			return candidate;
		} catch ( e ) {
			// Invalid tag, try the next candidate.
		}
	}
	return 'en';
} )();

