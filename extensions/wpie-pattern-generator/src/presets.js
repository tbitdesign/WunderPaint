export const PRESETS = LEGACY_PRESETS.map( ( p, i ) => ( {
	...p,
	id: 'classic-' + i,
	category: 'Classics',
} ) );
recipes.forEach( ( [ name, alt, category, motif, set, palette, count ], i ) => {
	const p = {
		...DEFAULTS,
		motif,
		set,
		palette,
		count,
		size: 72,
		weight: 26,
		variety: 65,
		seed: 101 + i * 37,
		jitter: 72,
		rot: 36,
		repeat: motif === 'scatter' ? 'halfdrop' : 'straight',
		freqI: 2,
		phase: 0,
		amp: 60,
	};
	if ( motif === 'scatter' )
		Object.assign( p, {
			distribution: i % 3 === 0 ? 'hero' : 'spaced',
			spacing: 65,
		} );
	if ( [ 'tartan', 'twill', 'houndstooth', 'argyle' ].includes( motif ) )
		Object.assign( p, { size: 80, weight: 32 } );
	PRESETS.push( { id: 'crafted-' + i + '-a', name, category, p } );
	const dense = {
		...p,
		count: motif === 'scatter' ? count + 8 : Math.min( 12, count + 2 ),
		size: motif === 'scatter' ? 64 : 84,
		weight: 38,
		variety: 85,
		seed: p.seed + 13,
		repeat: motif === 'scatter' ? 'third' : 'straight',
		aspect: i % 4 === 0 ? 1.4 : 1,
		amp: 78,
		freqI: 3,
		phase: 25,
	};
	if ( motif === 'scatter' )
		Object.assign( dense, {
			distribution: 'cluster',
			rot: 62,
			spacing: 30,
			set2:
				category === 'Botanical'
					? 'wildflowers'
					: category === 'Coastal'
					? 'seaweed'
					: '',
		} );
	if ( secondary[ category ] )
		dense.layers = [
			{
				...DEFAULTS,
				motif: secondary[ category ],
				count: 8,
				weight: 15,
				size: 25,
				amp: 35,
				freqI: 2,
				palette,
				alpha: 25,
				name: 'Ground',
			},
			{ ...dense, name: 'Motifs' },
		];
	PRESETS.push( {
		id: 'crafted-' + i + '-b',
		name: alt,
		category,
		p: dense,
	} );
} );
