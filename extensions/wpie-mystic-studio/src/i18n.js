/**
 * Translations. Two parts, deliberately side by side:
 *
 * 1. DICT (dict.js): UI chrome strings, English msgid -> translation
 *    (the usual studio pattern).
 * 2. CONTENT: language-dependent CHART DATA (sign names, keywords,
 *    planet and phase names), keyed by STABLE INDICES per language.
 *    Translators only ever see indices here - never translated keys.
 */

import { DICT } from './dict.js';

export const LOCALE = (
	( window.WPIE && window.WPIE.locale ) ||
	document.documentElement.lang ||
	'en'
).toLowerCase();

export const INTL_LOCALE = ( () => {
	const tag = LOCALE.replace( /_/g, '-' );
	for ( const candidate of [ tag, tag.split( '-' )[ 0 ], 'en' ] ) {
		try {
			Intl.DateTimeFormat.supportedLocalesOf( candidate );
			return candidate;
		} catch ( e ) {
			// Invalid tag, try the next one.
		}
	}
	return 'en';
} )();

