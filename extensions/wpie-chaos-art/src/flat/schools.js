/** Pick one vocabulary item by weight. */
export function pickVocab( items, rng, weightOf = null ) {
	if ( ! items || ! items.length ) {
		return null;
	}
	const wf = weightOf || ( ( it ) => it.w || 1 );
	const sum = items.reduce( ( a, b ) => a + wf( b ), 0 );
	if ( sum <= 0 ) {
		return items[ Math.floor( rng() * items.length ) % items.length ];
	}
	let r = rng() * sum;
	for ( const it of items ) {
		r -= wf( it );
		if ( r <= 0 ) {
			return it;
		}
	}
	return items[ items.length - 1 ];
}

/** Gesture scale (frame units) for a size class. */
export function sizeFor( cls, rng, mul = 1 ) {
	const R = {
		big: [ 0.16, 0.34 ],
		mid: [ 0.07, 0.15 ],
		small: [ 0.03, 0.07 ],
		accent: [ 0.012, 0.035 ],
	}[ cls ] || [ 0.05, 0.12 ];
	return ( R[ 0 ] + rng() * ( R[ 1 ] - R[ 0 ] ) ) * mul;
}

/** A value from a [lo, hi] range or a plain number. */
export const range = ( v, rng, dflt = 1 ) =>
	Array.isArray( v )
		? v[ 0 ] + rng() * ( v[ 1 ] - v[ 0 ] )
		: Number.isFinite( v )
		? v
		: dflt;
