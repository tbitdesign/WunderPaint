/**
 * The schools: how a movement paints, as a recipe the society follows
 * with its own temperament.
 *
 * A school is data, never a script: which palette taste, which ground,
 * which compositions it likes, how large and how fast its hands move,
 * and a VOCABULARY per phase - what kinds of marks its painters reach
 * for while the picture opens, builds, develops and finishes. The
 * painters decide when, where and how big; the school decides the
 * grammar. Add a school, get a new kind of picture.
 *
 * Painterly schools speak through the editor's own brush engine: a
 * `brush` item names media heads (the editor's 18 media brushes) and a
 * paint style, `wet: true` asks for the physics island. The schools
 * that are not brushes (geometry, torn paper, op lines) keep the own
 * marks of flat/marks.js.
 *
 * `phases` are fractions of the plan's coverage target at which the
 * picture moves on.
 */

