/**
 * Generate src/lib/license-texts.js from the plugin's license files, so the
 * About window can show the full License and Third-party license texts WITHOUT
 * any network call (the plugin makes no external requests). Re-run this after
 * editing license.txt or third-party-licenses.txt:
 *
 *   node tools/build-license-texts.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(
	path.dirname( fileURLToPath( import.meta.url ) ),
	'..'
);
const gpl = fs.readFileSync( path.join( root, 'license.txt' ), 'utf8' );
const third = fs.readFileSync(
	path.join( root, 'third-party-licenses.txt' ),
	'utf8'
);

/*
 * The External Services list comes out of readme.txt (v1.386.0) instead of
 * being written a second time: a second copy is exactly how a service ends up
 * documented in one place and forgotten in another. What the About window
 * shows is therefore literally what wordpress.org and every user reads.
 */
const readme = fs.readFileSync( path.join( root, 'readme.txt' ), 'utf8' );
const section = readme.match(
	/^== External Services ==\s*\n([\s\S]*?)(?=^== )/m
);
if ( ! section ) {
	console.error(
		'build-license-texts: readme.txt has no == External Services == section'
	);
	process.exit( 1 );
}
const services = section[ 1 ]
	.replace( /\*\*/g, '' ) // readme bold markers
	.replace( /^\* /gm, '- ' ) // readme bullets
	.trim();

const out =
	`/**\n` +
	` * Bundled license texts shown in the About window (no network call).\n` +
	` * GENERATED by tools/build-license-texts.mjs from license.txt,\n` +
	` * third-party-licenses.txt and the readme's External Services section -\n` +
	` * do not edit by hand.\n` +
	` */\n\n` +
	`/* eslint-disable */\n` +
	`export const LICENSE_GPL = ${ JSON.stringify( gpl ) };\n\n` +
	`export const LICENSE_THIRD_PARTY = ${ JSON.stringify( third ) };\n\n` +
	`export const EXTERNAL_SERVICES = ${ JSON.stringify( services ) };\n`;

fs.writeFileSync( path.join( root, 'src', 'lib', 'license-texts.js' ), out );

console.log(
	'wrote src/lib/license-texts.js',
	gpl.length + third.length + services.length,
	'chars'
);
